#!/usr/bin/env bash
# Store secrets as systemd encrypted credentials. Run on the Pi:
#
#   sudo bash scripts/set-credentials.sh            # Naukri username + password
#   sudo bash scripts/set-credentials.sh telegram   # Telegram bot token (if notify.provider = telegram)
#   sudo bash scripts/set-credentials.sh ntfy       # ntfy access token (only for protected topics)
#   sudo bash scripts/set-credentials.sh sync       # just regenerate the systemd drop-in
#
# Each secret is read with `read -s` (not echoed, not in shell history, not in argv) and piped
# straight into `systemd-creds encrypt`. Only the encrypted *.cred files touch the disk.
#
# Without a TPM (the Pi has none) systemd encrypts with the host key
# /var/lib/systemd/credential.secret. That protects against casual reads, copied SD-card
# images of /etc only, and backups - NOT against root on the Pi, who can decrypt.
set -euo pipefail
set +x # never trace this script; it handles secrets

CRED_DIR=/etc/naukri-refresher/creds
DROPIN_DIR=/etc/systemd/system/naukri-refresher.service.d
DROPIN="$DROPIN_DIR/credentials.conf"

die() { echo "error: $*" >&2; exit 1; }
[ "$(id -u)" -eq 0 ] || die "run with sudo"
command -v systemd-creds >/dev/null || die "systemd-creds not found (needs systemd >= 250; Bookworm has 252)"

install -d -m 0700 -o root -g root "$CRED_DIR"

encrypt() { # name prompt hide(0/1)
  local name="$1" prompt="$2" hide="$3" value=""
  if [ "$hide" = 1 ]; then
    read -r -s -p "$prompt: " value; echo
  else
    read -r -p "$prompt: " value
  fi
  [ -n "$value" ] || die "$name must not be empty"
  # printf is a bash builtin: the secret never appears in a process argument list.
  printf '%s' "$value" | systemd-creds encrypt --name="$name" - "$CRED_DIR/$name.cred.tmp"
  value=""
  chmod 0600 "$CRED_DIR/$name.cred.tmp"
  mv -f "$CRED_DIR/$name.cred.tmp" "$CRED_DIR/$name.cred"
  echo "stored $CRED_DIR/$name.cred (encrypted)"
}

sync_dropin() {
  install -d -m 0755 "$DROPIN_DIR"
  {
    echo "# Generated by scripts/set-credentials.sh - do not edit."
    echo "[Service]"
    for f in "$CRED_DIR"/*.cred; do
      [ -e "$f" ] || continue
      n="$(basename "$f" .cred)"
      echo "LoadCredentialEncrypted=$n:$f"
    done
  } >"$DROPIN.tmp"
  chmod 0644 "$DROPIN.tmp"
  mv -f "$DROPIN.tmp" "$DROPIN"
  systemctl daemon-reload
  echo "updated $DROPIN"
}

case "${1:-naukri}" in
  naukri)
    encrypt naukri-username "Naukri email / username" 0
    encrypt naukri-password "Naukri password (input hidden)" 1
    ;;
  telegram) encrypt telegram-bot-token "Telegram bot token (input hidden)" 1 ;;
  ntfy) encrypt ntfy-token "ntfy access token (input hidden)" 1 ;;
  sync) ;;
  *) die "unknown target '$1' (naukri | telegram | ntfy | sync)" ;;
esac
sync_dropin
